using CKAN;
using CKAN.Games.KerbalSpaceProgram;
using VmpLauncher.Ckan.Locking;
using VmpLauncher.Ckan.Users;
using VmpLauncher.Core;
using VmpLauncher.Core.Hashing;
using VmpLauncher.Core.Locking;
using VmpLauncher.Core.Packs;

namespace VmpLauncher.Publishing;

/// <summary>
/// Classifies every file in the host's GameData so the export knows what is CKAN-owned, custom, an override,
/// generated, per-player, or unknown. Nothing unknown is ever shipped; a host must add a rule or an override.
/// </summary>
public sealed class HostCapture
{
    public enum Class
    {
        Stock,
        Generated,
        PerPlayer,
        CkanOwned,
        RuntimeMutated,
        OverrideReplace,
        Custom,
        OverrideDisable,
        MissingOwned,
        OverrideAdd,
        Unknown,
    }

    public sealed record Row(string Path, Class Class, string? Owner, string? Detail);

    public sealed record Result(IReadOnlyList<Row> Rows, IReadOnlyList<LockOverride> Overrides, IReadOnlyList<string> Errors)
    {
        public IEnumerable<Row> Of(Class c) => Rows.Where(r => r.Class == c);
        public int Count(Class c) => Rows.Count(r => r.Class == c);
    }

    private static readonly string[] ManagedRoots = { "GameData", "Ships", "Missions" };
    private readonly TextWriter _log;

    public HostCapture(TextWriter log)
    {
        _log = log;
    }

    public Result Run(string hostKspDir, string hostCacheDir, PackDefinition pack, string packDir, LauncherPaths paths, bool acceptOverrides, CancellationToken ct = default)
    {
        var rows = new List<Row>();
        var overrides = new List<LockOverride>();
        var errors = new List<string>();
        var rules = new FileRuleSet(pack.FileRules);
        var game = new KerbalSpaceProgram();
        var user = new VmpCkanUser();
        var repoData = new RepositoryDataManager(paths.CkanReposDir);
        var inst = new GameInstance(game, hostKspDir, "host", user);
        var registry = RegistryManager.ReadOnlyRegistry(inst, repoData) ?? throw new InvalidOperationException("Cannot read the host registry.");
        var indexer = new ArchiveContentIndexer(Path.Combine(paths.DataRoot, "capture-cache.json"), game);

        // Expected content from archives, keyed by path.
        var expected = new Dictionary<string, (string Owner, long Size, string Sha256)>(StringComparer.OrdinalIgnoreCase);
        using (var cache = new NetModuleCache(hostCacheDir))
        {
            foreach (var im in registry.InstalledModules.Where(m => !m.Module.IsDLC && !m.Module.IsMetapackage))
            {
                ct.ThrowIfCancellationRequested();
                var zip = cache.GetCachedFilename(im.Module);
                if (zip is null)
                {
                    errors.Add($"{im.identifier}: archive not in cache; cannot classify its files");
                    continue;
                }
                var metaSha = JsonCanonicalizer.Sha256(im.Module.ToJson());
                foreach (var ef in indexer.Index(im.Module, zip, metaSha, ct))
                {
                    expected[ef.Path] = (im.identifier, ef.Size, ef.Sha256);
                }
            }
        }
        indexer.Save();

        var customRoots = pack.CustomPackages.Select(c => c.InstallAs.Replace('\\', '/').TrimEnd('/') + "/").ToList();
        var declaredOverrides = pack.Overrides.ToDictionary(o => o.Path.Replace('\\', '/'), StringComparer.OrdinalIgnoreCase);
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        // CKAN installs into GameData, Ships and Missions, plus (rarely) the game root; walk the same roots.
        IEnumerable<string> candidates = ManagedRoots
            .Select(r => Path.Combine(hostKspDir, r))
            .Where(Directory.Exists)
            .SelectMany(r => Directory.EnumerateFiles(r, "*", SearchOption.AllDirectories));
        candidates = candidates.Concat(expected.Keys.Where(k => !k.Contains('/')).Select(k => Path.Combine(hostKspDir, k)).Where(File.Exists));
        foreach (var file in candidates)
        {
            ct.ThrowIfCancellationRequested();
            var rel = Path.GetRelativePath(hostKspDir, file).Replace('\\', '/');
            seen.Add(rel);
            if (rules.Stock.IsMatch(rel)) { rows.Add(new Row(rel, Class.Stock, null, null)); continue; }
            if (rules.Generated.IsMatch(rel)) { rows.Add(new Row(rel, Class.Generated, null, null)); continue; }
            if (rules.PerPlayer.IsMatch(rel)) { rows.Add(new Row(rel, Class.PerPlayer, null, null)); continue; }
            if (!expected.ContainsKey(rel) && rules.MutableOwned.IsMatch(rel) && !customRoots.Any(r => rel.StartsWith(r, StringComparison.OrdinalIgnoreCase)))
            {
                // Unowned file in a mod's runtime-state location: generated by the mod, not content to ship.
                rows.Add(new Row(rel, Class.Generated, null, "runtime state"));
                continue;
            }
            if (expected.TryGetValue(rel, out var exp))
            {
                var fi = new FileInfo(file);
                var same = fi.Length == exp.Size && Sha256Util.HexEquals(Sha256Util.HashFile(file, ct), exp.Sha256);
                if (same) { rows.Add(new Row(rel, Class.CkanOwned, exp.Owner, null)); continue; }
                if (rules.MutableOwned.IsMatch(rel)) { rows.Add(new Row(rel, Class.RuntimeMutated, exp.Owner, "runtime-mutated; archive content shipped")); continue; }
                var actualSha = Sha256Util.HashFile(file, ct);
                rows.Add(new Row(rel, Class.OverrideReplace, exp.Owner, acceptOverrides ? "replace override recorded" : "modified managed file; needs --accept-overrides"));
                if (acceptOverrides)
                {
                    var bytes = File.ReadAllBytes(file);
                    overrides.Add(new LockOverride
                    {
                        Id = "ovr-replace-" + Sha256Util.HashUtf8(rel)[..8],
                        Op = "replace", Path = rel, Owner = exp.Owner, BaseSha256 = exp.Sha256, Sha256 = actualSha, Size = bytes.Length,
                        Content = bytes.Length <= 64 * 1024 ? new OverrideContent { InlineBase64 = Convert.ToBase64String(bytes) } : null,
                    });
                    if (bytes.Length > 64 * 1024)
                    {
                        errors.Add($"{rel}: replace override larger than 64 KiB; override bundles are not implemented yet");
                    }
                }
                continue;
            }
            if (customRoots.Any(r => rel.StartsWith(r, StringComparison.OrdinalIgnoreCase))) { rows.Add(new Row(rel, Class.Custom, customRoots.First(r => rel.StartsWith(r, StringComparison.OrdinalIgnoreCase)), null)); continue; }
            if (rel.EndsWith(".disabled", StringComparison.OrdinalIgnoreCase) && expected.TryGetValue(rel[..^".disabled".Length], out var orig))
            {
                var origPath = rel[..^".disabled".Length];
                var sha = Sha256Util.HashFile(file, ct);
                if (Sha256Util.HexEquals(sha, orig.Sha256))
                {
                    rows.Add(new Row(rel, Class.OverrideDisable, orig.Owner, $"disables {origPath}"));
                    overrides.Add(new LockOverride { Id = "ovr-disable-" + Sha256Util.HashUtf8(origPath)[..8], Op = "disable", Path = origPath, Owner = orig.Owner, BaseSha256 = orig.Sha256, RenameTo = Path.GetFileName(rel) });
                    continue;
                }
            }
            if (declaredOverrides.TryGetValue(rel, out var decl) && decl.Op == "add")
            {
                var bytes = File.ReadAllBytes(file);
                rows.Add(new Row(rel, Class.OverrideAdd, null, "declared add override"));
                overrides.Add(new LockOverride
                {
                    Id = "ovr-add-" + Sha256Util.HashUtf8(rel)[..8], Op = "add", Path = rel, Sha256 = Sha256Util.HashBytes(bytes), Size = bytes.Length,
                    Content = new OverrideContent { InlineBase64 = Convert.ToBase64String(bytes) },
                });
                continue;
            }
            if (!rel.StartsWith("GameData/", StringComparison.OrdinalIgnoreCase))
            {
                // Stock craft / mission files outside GameData are seeded from the player's own install.
                rows.Add(new Row(rel, Class.Stock, null, "outside GameData"));
                continue;
            }
            rows.Add(new Row(rel, Class.Unknown, null, rel.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) ? "UNKNOWN DLL" : null));
        }
        // Owned files missing from disk (not explained by a .disabled twin)
        foreach (var (path, exp) in expected)
        {
            if (!seen.Contains(path) && !seen.Contains(path + ".disabled"))
            {
                rows.Add(new Row(path, Class.MissingOwned, exp.Owner, "owned file missing on host"));
            }
        }
        var unknownDlls = rows.Where(r => r.Class == Class.Unknown && r.Path.EndsWith(".dll", StringComparison.OrdinalIgnoreCase)).ToList();
        if (unknownDlls.Count > 0)
        {
            errors.Add($"{unknownDlls.Count} unknown DLL(s) in GameData would be rejected by the server policy: {string.Join(", ", unknownDlls.Take(5).Select(u => u.Path))}");
        }
        if (rows.Any(r => r.Class == Class.MissingOwned))
        {
            var missing = rows.Where(r => r.Class == Class.MissingOwned).ToList();
            errors.Add($"{missing.Count} CKAN-owned file(s) are missing on the host (repair the host install with CKAN first): {string.Join(", ", missing.Take(8).Select(m => $"{m.Path} ({m.Owner})"))}");
        }
        var unknownAll = rows.Where(r => r.Class == Class.Unknown).ToList();
        if (unknownAll.Count > 0)
        {
            var byTop = unknownAll.GroupBy(r => string.Join('/', r.Path.Split('/').Take(2))).OrderByDescending(g => g.Count()).Take(12);
            _log.WriteLine($"Unknown files by top folder: {string.Join(", ", byTop.Select(g => $"{g.Key} ({g.Count()})"))}");
        }
        if (!acceptOverrides && rows.Any(r => r.Class == Class.OverrideReplace))
        {
            errors.Add($"{rows.Count(r => r.Class == Class.OverrideReplace)} managed file(s) are modified on the host; re-run with --accept-overrides to ship them as deliberate overrides, or restore them");
        }
        _log.WriteLine($"Capture: {rows.Count} files; " + string.Join(", ", Enum.GetValues<Class>().Select(c => $"{c} {rows.Count(r => r.Class == c)}").Where(s => !s.EndsWith(" 0", StringComparison.Ordinal))));
        return new Result(rows, overrides, errors);
    }
}
